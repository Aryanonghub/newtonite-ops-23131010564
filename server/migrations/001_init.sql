-- Initial schema. Allowed values use CHECK constraints (easier to change than Postgres ENUM types).

CREATE EXTENSION IF NOT EXISTS pg_trgm; -- trigram index for fast "contains" text search

CREATE TABLE users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         TEXT NOT NULL UNIQUE,
  name          TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE teams (
  id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE
);

-- A user can be in many teams, with a different role in each.
CREATE TABLE memberships (
  user_id INT  NOT NULL REFERENCES users(id),
  team_id INT  NOT NULL REFERENCES teams(id),
  role    TEXT NOT NULL CHECK (role IN ('viewer', 'member', 'lead', 'admin')),
  PRIMARY KEY (user_id, team_id)          -- also serves "which teams is this user in?"
);
CREATE INDEX memberships_team_idx ON memberships (team_id);

CREATE TABLE work_items (
  id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       TEXT NOT NULL CHECK (length(title) BETWEEN 1 AND 200),
  description TEXT NOT NULL DEFAULT '',
  type        TEXT NOT NULL CHECK (type IN ('incident', 'customer_issue', 'payment', 'compliance', 'task')),
  priority    TEXT NOT NULL CHECK (priority IN ('low', 'medium', 'high', 'urgent')),
  status      TEXT NOT NULL DEFAULT 'open'
              CHECK (status IN ('open', 'in_progress', 'awaiting_approval', 'resolved', 'closed')),
  team_id     INT  NOT NULL REFERENCES teams(id),
  assignee_id INT  REFERENCES users(id),  -- NULL = unassigned
  created_by  INT  NOT NULL REFERENCES users(id),
  due_date    DATE,
  version     INT  NOT NULL DEFAULT 1 CHECK (version > 0),  -- optimistic locking counter
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- List indexes. Every list query is scoped to the user's teams and sorted by
-- (created_at DESC, id DESC) for cursor pagination, so team_id leads and the sort keys trail.
CREATE INDEX work_items_team_created_idx  ON work_items (team_id, created_at DESC, id DESC);
CREATE INDEX work_items_team_status_idx   ON work_items (team_id, status, created_at DESC, id DESC);
CREATE INDEX work_items_team_priority_idx ON work_items (team_id, priority, created_at DESC, id DESC);
-- "Assigned to me" and the assignee filter.
CREATE INDEX work_items_assignee_idx      ON work_items (assignee_id, status);
-- "Unassigned urgent": a small partial index containing only those rows.
CREATE INDEX work_items_unassigned_urgent_idx ON work_items (team_id, created_at DESC)
  WHERE assignee_id IS NULL AND priority = 'urgent';
-- Search: title ILIKE '%text%' can use a trigram GIN index (a normal B-tree cannot).
CREATE INDEX work_items_title_trgm_idx    ON work_items USING gin (title gin_trgm_ops);

CREATE TABLE comments (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id    INT  NOT NULL REFERENCES work_items(id),
  author_id  INT  NOT NULL REFERENCES users(id),
  body       TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 5000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX comments_item_idx ON comments (item_id, id);

-- Append-only history. Written in the same transaction as the change it describes.
CREATE TABLE activity_events (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_id    INT  NOT NULL REFERENCES work_items(id),
  actor_id   INT  NOT NULL REFERENCES users(id),
  kind       TEXT NOT NULL CHECK (kind IN
               ('created', 'status_changed', 'assignee_changed', 'priority_changed', 'edited', 'commented')),
  from_value TEXT,
  to_value   TEXT,
  comment_id INT REFERENCES comments(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX activity_events_item_idx ON activity_events (item_id, id);

-- Enforce append-only in the database itself, not just in app code.
CREATE FUNCTION reject_change() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER activity_events_append_only
  BEFORE UPDATE OR DELETE ON activity_events
  FOR EACH ROW EXECUTE FUNCTION reject_change();

-- Stored responses for POST requests that carry an Idempotency-Key header.
CREATE TABLE idempotency_keys (
  user_id         INT  NOT NULL REFERENCES users(id),
  key             TEXT NOT NULL,
  request_hash    TEXT NOT NULL,   -- detects "same key, different request"
  response_status INT,             -- filled in at the end of the same transaction
  response_body   JSONB,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, key)       -- the UNIQUE(user_id, key) rule
);

-- Transactional outbox: jobs inserted in the same transaction as the change.
CREATE TABLE outbox_jobs (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         TEXT NOT NULL,
  payload      JSONB NOT NULL,
  status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done', 'failed')),
  attempts     INT  NOT NULL DEFAULT 0,
  max_attempts INT  NOT NULL DEFAULT 5,
  run_after    TIMESTAMPTZ NOT NULL DEFAULT now(),  -- used for retry backoff
  last_error   TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- The worker only looks at pending jobs, so index only those.
CREATE INDEX outbox_jobs_pending_idx ON outbox_jobs (run_after) WHERE status = 'pending';
