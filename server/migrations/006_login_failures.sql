-- Failed logins, for rate limiting. Kept in the database (not in memory) so the limit holds across
-- several API processes, e.g. many Vercel function instances at once.
CREATE TABLE login_failures (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email      TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX login_failures_email_idx ON login_failures (email, created_at DESC);
